/**
 * Writes deploy version metadata used at build time.
 *
 * Every build gets a unique label:
 *   v{package.version}+{commitCount}  (e.g. v1.1.0+1523)
 *   or on CI: v{package.version}+run.{GITHUB_RUN_NUMBER}
 *
 * Set KATOA_BUMP_PACKAGE=1 to also bump package.json patch (recommended
 * before each intentional ship from M3 agents).
 *
 * Outputs:
 *   src/generated/app-version.ts  (compile-time input for the footer label)
 *
 * The deploy-facing artifacts (dist/sw.js, dist/version.json) are filled from
 * the public/ seeds AFTER `vite build` by scripts/fill-dist-artifacts.mjs, so
 * no tracked file is ever mutated by a build.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bumpPatch, getVersionInfo } from './version-util.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const pkgPath = join(root, 'package.json');

const { pkg, version } = getVersionInfo(root);
const previous = pkg.version || '1.0.0';
const shouldBump =
  process.env.KATOA_BUMP_PACKAGE === '1' ||
  process.env.KATOA_BUMP_PACKAGE === 'true' ||
  process.argv.includes('--bump');

let next = version;

if (shouldBump && !process.env.KATOA_VERSION_OVERRIDE) {
  next = bumpPatch(previous);
  pkg.version = next;
  writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');
}

const info = getVersionInfo(root);

const ts = `/** Auto-generated by scripts/write-version.mjs — do not edit */
export const APP_VERSION = ${JSON.stringify(next)};
export const APP_VERSION_LABEL = ${JSON.stringify(info.label)};
export const APP_BUILD_ID = ${JSON.stringify(String(info.buildId))};
export const APP_VERSION_FULL = ${JSON.stringify(info.fullLabel)};
export const APP_BUILT_AT = ${JSON.stringify(info.builtAt)};
export const APP_GIT_SHA = ${JSON.stringify(info.gitSha)};
export const APP_GIT_COMMIT_COUNT = ${JSON.stringify(info.gitCount)};
`;

const genDir = join(root, 'src', 'generated');
mkdirSync(genDir, { recursive: true });
writeFileSync(join(genDir, 'app-version.ts'), ts, 'utf8');

console.log(`version: ${previous}${shouldBump ? ` → ${next}` : ''}  footer: ${info.fullLabel}`);
